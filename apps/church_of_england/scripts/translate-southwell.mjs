#!/usr/bin/env node
/**
 * Translate Southwell Minster page copy via DeepL API.
 *
 * Usage:
 *   node scripts/translate-southwell.mjs
 *   node scripts/translate-southwell.mjs --lang fr
 *   node scripts/translate-southwell.mjs --langs fr,de,es --dry-run
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { ARTWORK_LOCALE_TARGETS } from "./artwork-locales.config.mjs"
import { countCharacters, getDeepLUsage, translateTexts } from "./lib/deepl.mjs"
import { loadEnvLocal } from "./lib/load-env.mjs"

loadEnvLocal()

const __dirname = dirname(fileURLToPath(import.meta.url))
const appRoot = join(__dirname, "..")
const sourcePath = join(appRoot, "src/data/southwellMinster.en.json")

const SKIP_KEYS = new Set([
  "name",
  "href",
  "year",
  "num",
  "donateHref",
  "latinColophon",
  "addressLines",
  "telephone",
  "telephoneDisplay",
  "email",
  "websiteUrl",
  "websiteDisplay",
  "urgentTel",
  "urgentDisplay",
  "shopTel",
  "shopTelDisplay",
  "shopEmail",
  "facebookUrl",
  "twitterUrl",
  "instagramUrl",
  "facebook",
  "twitter",
  "instagram",
  "clock",
])

const args = process.argv.slice(2)
const dryRun = args.includes("--dry-run")
const onlyLang = args.includes("--lang") ? args[args.indexOf("--lang") + 1] : null
const onlyLangs = args.includes("--langs") ? args[args.indexOf("--langs") + 1] : null

const apiKey = process.env.DEEPL_API_KEY
const apiUrl = process.env.DEEPL_API_URL ?? "https://api-free.deepl.com"

const TARGETS = ARTWORK_LOCALE_TARGETS.map((entry) => ({
  code: entry.deepl,
  locale: entry.locale,
  exportName: `SOUTHWELL_MINSTER_${entry.locale.toUpperCase()}`,
  fileName: `southwellMinster.${entry.locale}.ts`,
  label: entry.label,
}))

function flattenCopy(value, path = "") {
  const jobs = []
  const keys = []
  const push = (key, text) => {
    if (text == null || text === "") return
    keys.push(key)
    jobs.push(text)
  }

  const walk = (node, currentPath) => {
    if (typeof node === "string") {
      push(currentPath, node)
      return
    }
    if (Array.isArray(node)) {
      const leaf = currentPath.split(".").pop()
      if (SKIP_KEYS.has(leaf)) return
      node.forEach((item, index) => walk(item, `${currentPath}.${index}`))
      return
    }
    if (node && typeof node === "object") {
      for (const [key, child] of Object.entries(node)) {
        if (SKIP_KEYS.has(key)) continue
        walk(child, currentPath ? `${currentPath}.${key}` : key)
      }
    }
  }

  walk(value, path)
  return { jobs, keys }
}

function setAtPath(target, path, value) {
  const parts = path.split(".")
  let cursor = target
  for (let i = 0; i < parts.length - 1; i++) {
    const part = parts[i]
    const next = parts[i + 1]
    const nextIsIndex = /^\d+$/.test(next)
    if (cursor[part] == null) cursor[part] = nextIsIndex ? [] : {}
    cursor = cursor[part]
  }
  cursor[parts[parts.length - 1]] = value
}

function rebuildCopy(source, keys, translated) {
  const next = structuredClone(source)
  keys.forEach((key, index) => {
    setAtPath(next, key, decodeEntities(translated[index] ?? getAtPath(source, key)))
  })
  return next
}

function decodeEntities(value) {
  if (typeof value !== "string") return value
  return value
    .replace(/&#x27;|&#39;|&apos;/gi, "'")
    .replace(/&quot;/g, '"')
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/&lsquo;|&rsquo;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
}

function getAtPath(source, path) {
  return path.split(".").reduce((cursor, part) => cursor?.[part], source)
}

function toTsFile(exportName, copy, langLabel) {
  return `import type { SouthwellMinsterCopy } from "./southwellMinster"

/** ${langLabel} copy — generated by scripts/translate-southwell.mjs (review before publishing). */
export const ${exportName}: SouthwellMinsterCopy = ${JSON.stringify(copy, null, 2)}
`
}

function filterTargets() {
  if (onlyLangs) {
    const wanted = new Set(onlyLangs.split(",").map((value) => value.trim().toLowerCase()))
    return TARGETS.filter(
      (target) => wanted.has(target.locale) || wanted.has(target.code.toLowerCase()),
    )
  }
  if (onlyLang) {
    const wanted = onlyLang.trim().toLowerCase()
    return TARGETS.filter(
      (target) => target.locale === wanted || target.code.toLowerCase() === wanted,
    )
  }
  return TARGETS
}

if (!dryRun && !apiKey) {
  console.error("Set DEEPL_API_KEY in apps/church_of_england/.env.local")
  process.exit(1)
}

const source = JSON.parse(readFileSync(sourcePath, "utf8"))
const { jobs, keys } = flattenCopy(source)
const targets = filterTargets()

if (targets.length === 0) {
  console.error("Unknown language filter; use --lang fr or --langs fr,de,es")
  process.exit(1)
}

console.log(
  `Translating Southwell Minster, ${jobs.length} strings, ~${countCharacters(jobs)} characters → ${targets.map((t) => t.code).join(", ")}`,
)

if (dryRun) process.exit(0)

try {
  const usage = await getDeepLUsage(apiKey, apiUrl)
  console.log(
    `DeepL usage: ${usage.character_count} / ${usage.character_limit} characters this billing period`,
  )
} catch (error) {
  console.warn(`Could not fetch usage: ${error.message}`)
}

for (const target of targets) {
  console.log(`translate → ${target.code}...`)
  const translated = await translateTexts(jobs, {
    apiKey,
    apiUrl,
    targetLang: target.code,
    tagHandling: "html",
  })
  const copy = rebuildCopy(source, keys, translated)
  const contents = toTsFile(target.exportName, copy, target.label)
  const outPath = join(appRoot, "src/data", target.fileName)
  writeFileSync(outPath, contents)
  console.log(`  wrote ${outPath}`)
  await new Promise((r) => setTimeout(r, 300))
}

console.log("\nReview translated copy, then wire locale resolvers if needed.")
