const COPY: Record<ArtworkPageLocale, UiCopy> = {
  en: EN,
  fr: FR,
  ja: JA,
  ar: AR,
  de: DE,
  es: ES,
  ko: KO,
  zh: ZH,
  pt: PT,
  tr: TR,
  it: IT,
}

export function uiCopy(locale: ArtworkPageLocale): UiCopy {
  return COPY[locale]
}

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => values[key] ?? "")
}

export function formatPrice(price: string, copy: UiCopy): string {
  if (price.startsWith("Under ")) return fill(copy.underPrice, { price: price.slice("Under ".length) })
  return price
}

export function priceLabel(price: string, copy: UiCopy): string {
  return price.startsWith("Under") ? copy.priceRange : copy.price
}
